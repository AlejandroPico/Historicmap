import{test,expect,type Page}from'@playwright/test';
async function date(page:Page,y:number){await page.locator('#date-button').click();await page.locator('#date-input').fill(String(y));await page.locator('#date-form button').click();await expect(page.locator('#planet-panel')).toHaveAttribute('data-year',String(y));}
test('planet panel retains its tab and date, identifies dated references and geological unknowns',async({page},testInfo)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/#year=2026&view=mercator');
 await expect(page.locator('#map')).toHaveAttribute('data-loaded-year','2026',{timeout:90000});
 await page.locator('#search-button').click();await page.locator('#search-input').fill('España');await page.locator('#search-results button').first().click();
 await expect(page.locator('#selection')).toBeVisible();
 await page.locator('#planet-button').click();
 await expect(page.locator('#planet-panel')).toBeVisible();
 await expect(page.locator('[data-indicator="temperatureAnomaly"]')).toContainText('1,43 ± 0,13');
 await expect(page.locator('[data-indicator="temperatureAnomaly"]')).toHaveAttribute('data-reference-year','2025');
 if(process.env.EARTH_QA_SCREENSHOTS)await page.screenshot({path:testInfo.outputPath('planet-modern.png'),timeout:45000,animations:'disabled'});
 await page.getByRole('tab',{name:'Cronología',exact:true}).click();
 await expect(page.locator('[data-geological-unit="Holocene"]')).toBeVisible();
 await expect(page.locator('#map')).toHaveAttribute('data-loaded-year','1',{timeout:90000});
 await date(page,-100000000);
 await expect(page.getByRole('tab',{name:'Cronología',exact:true})).toHaveAttribute('aria-selected','true');
 await expect(page.locator('[data-geological-unit="Cretaceous"]')).toBeVisible();
 await expect(page.locator('#chronology-bands')).toHaveAttribute('data-mode','geological');
 await expect(page.locator('#selection')).toBeVisible();
 await page.getByRole('tab',{name:'Planeta',exact:true}).click();
 await expect(page.locator('#planet-content')).toContainText('Sin composición atmosférica');
 await expect(page.locator('#planet-content')).not.toContainText('≈ 78');
 await page.getByRole('tab',{name:'Fuentes',exact:true}).click();
 await date(page,-4540000000);await expect(page.locator('#planet-panel')).toBeVisible();
 await expect(page.getByRole('tab',{name:'Fuentes',exact:true})).toHaveAttribute('aria-selected','true');
 await page.getByRole('tab',{name:'Cronología',exact:true}).click();
 await expect(page.locator('[data-geological-unit="Hadean"]')).toBeVisible();
 if(process.env.EARTH_QA_SCREENSHOTS)await page.screenshot({path:testInfo.outputPath('planet-hadean.png'),timeout:45000,animations:'disabled'});
 expect(errors).toEqual([]);
});
test('compact bands, colour persistence, keyboard tabs and projection work on a narrow screen',async({page},testInfo)=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/#year=2026&view=mercator');
 await expect(page.locator('#map')).toHaveAttribute('data-loaded-year','2026',{timeout:90000});
 await page.locator('#layers-button').click();
 await expect(page.locator('#chronology-colors')).toHaveAttribute('aria-pressed','true');
 await page.locator('#chronology-colors').click();
 await expect(page.locator('.time-dock')).toHaveAttribute('data-chronology-colors','false');
 await page.reload();await expect(page.locator('.time-dock')).toHaveAttribute('data-chronology-colors','false');
 await page.locator('#planet-button').click();
 await page.getByRole('tab',{name:'Planeta',exact:true}).focus();await page.keyboard.press('ArrowRight');
 await expect(page.getByRole('tab',{name:'Cronología',exact:true})).toBeFocused();
 if(process.env.EARTH_QA_SCREENSHOTS)await page.screenshot({path:testInfo.outputPath('planet-mobile.png'),timeout:45000,animations:'disabled'});
 await date(page,-1);await page.locator('#next').click();
 await expect(page.locator('#planet-panel')).toHaveAttribute('data-year','1');
 await expect(page.locator('[data-geological-unit="Holocene"]')).toBeVisible();
 await page.locator('#projection-button').click();
 await expect(page.locator('#projection-button')).toHaveAttribute('data-view','globe');
 await expect(page.locator('#planet-panel')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
 const years=(await page.locator('.tick.major').first().boundingBox())!,bands=(await page.locator('#chronology-bands').boundingBox())!;
 expect(bands.y+bands.height).toBeLessThan(years.y);
 await page.setViewportSize({width:844,height:390});
 await expect(page.locator('#map')).toHaveAttribute('aria-busy','false',{timeout:90000});
 await expect(page.locator('#map')).toHaveAttribute('data-camera-ready','true',{timeout:90000});
 await expect(page.locator('#planet-panel')).toBeVisible();
 expect((await page.locator('#planet-content').boundingBox())!.height).toBeGreaterThan(50);
 if(process.env.EARTH_QA_SCREENSHOTS)await page.screenshot({path:testInfo.outputPath('planet-landscape.png'),timeout:45000,animations:'disabled'});
 await page.keyboard.press('Escape');await expect(page.locator('#planet-panel')).toBeHidden();
 await expect(page.locator('#planet-button')).toBeFocused();
});
